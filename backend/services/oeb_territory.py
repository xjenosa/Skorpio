"""
Point-in-polygon territory check against the OEB Distributor Service
Territories dataset.

Replaces the previous 40 km substation-radius proxy in grid/generator.py
with a real boundary check: a candidate is "in Alectra's territory" iff
its (lat, lon) falls inside one of Alectra's official OEB franchise
polygons. Per REPORTS_COHESION.md §0, this trades a documented heuristic
for the real boundary the regulator publishes.

Polygon data lives in _oeb_territories_generated.py (auto-generated by
backend/scripts/ingest_oeb_territories.py from the OEB KMZ). This module
just provides the lookup + point-in-polygon math; rerun the ingest
script after an OEB dataset refresh.

The runtime cost of a single point-in-polygon check is O(V) for V
vertices in the named utility's MultiPolygon. Hydro One is the worst
case (~101k vertices) and runs in ~5 ms on a modern CPU. The bbox
short-circuit at the top of `point_in_territory` makes most rejections
constant-time. No external dependencies — stdlib only.
"""
from __future__ import annotations

from typing import Optional

from backend.services._oeb_territories_generated import TERRITORIES


# Map the lowercase utility keys used everywhere else in the pipeline
