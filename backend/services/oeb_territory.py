def _oeb_name_for(utility_key: str) -> Optional[str]:
    """Look up the OEB canonical name for a colloquial utility key, with a
    case-insensitive substring fallback against TERRITORIES keys so a new
    LDC added to _UTILITY_TO_PROVINCE works without a code change here."""
    if not utility_key:
        return None
    key = utility_key.strip().lower()
    if key in _KEY_TO_OEB_NAME:
        return _KEY_TO_OEB_NAME[key]
    # Substring fallback — first OEB name containing the key string.
    for oeb_name in TERRITORIES:
        if key in oeb_name.lower():
            return oeb_name
    return None


def _point_in_ring(lon: float, lat: float, ring: list[tuple[float, float]]) -> bool:
    """Standard ray-casting point-in-polygon. Ring is a list of (lon, lat)
    tuples; the polygon is assumed closed (first == last) or implicitly
    closed by the algorithm. Points exactly on an edge are treated as
    inside, which matches GIS convention for franchise-boundary lookups
    (a customer ON the boundary line is served by the utility on either
    side; the OEB resolves these case-by-case, so "inside" is the safer
    default here)."""
    n = len(ring)
    if n < 3:
        return False
    inside = False
    j = n - 1
    for i in range(n):
        xi, yi = ring[i]
        xj, yj = ring[j]
        # Standard half-open ray-cast. The `(yi > lat) != (yj > lat)` test
        # avoids double-counting vertices at the ray's latitude.
        intersects = ((yi > lat) != (yj > lat)) and (
            lon < (xj - xi) * (lat - yi) / (yj - yi + 1e-12) + xi
        )
        if intersects:
            inside = not inside
        j = i
    return inside


def point_in_territory(lat: float, lon: float, utility_key: str) -> bool:
    """True iff (lat, lon) falls inside any of the named utility's OEB
    franchise polygons. Returns False when the utility key isn't in the
    OEB dataset (e.g. a BC / AB utility named in the prompt — the caller
    should fall back to substation-proximity routing in that case)."""
    oeb_name = _oeb_name_for(utility_key)
    if oeb_name is None:
        return False
    entry = TERRITORIES.get(oeb_name)
    if entry is None:
        return False

    # Bbox short-circuit — most rejections are constant-time.
    min_lat, min_lon, max_lat, max_lon = entry["bbox"]
    if lat < min_lat or lat > max_lat or lon < min_lon or lon > max_lon:
        return False

    # Point-in-polygon for each MultiPolygon patch. Inside any outer ring
    # AND not inside any hole within that ring = inside the patch.
    for patch in entry["polygons"]:
        if not patch:
            continue
        outer = patch[0]
        if not _point_in_ring(lon, lat, outer):
            continue
        # In an outer ring — check holes.
        in_hole = False
        for hole in patch[1:]:
            if _point_in_ring(lon, lat, hole):
                in_hole = True
                break
        if not in_hole:
            return True
    return False


def has_polygon_for(utility_key: str) -> bool:
    """True iff the OEB dataset has polygons for the named utility. Used by
    the caller to decide whether to use polygon-based routing or fall
    back to the substation-proximity proxy."""
    return _oeb_name_for(utility_key) is not None
